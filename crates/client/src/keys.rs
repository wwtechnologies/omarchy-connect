use eframe::egui::Key;
use omarchy_protocol::keys;

pub fn evdev_code(key: Key) -> Option<u16> {
    Some(match key {
        Key::Escape => keys::KEY_ESC,
        Key::Tab => keys::KEY_TAB,
        Key::Backspace => keys::KEY_BACKSPACE,
        Key::Enter => keys::KEY_ENTER,
        Key::Space => keys::KEY_SPACE,
        Key::Insert => keys::KEY_INSERT,
        Key::Delete => keys::KEY_DELETE,
        Key::Home => keys::KEY_HOME,
        Key::End => keys::KEY_END,
        Key::PageUp => keys::KEY_PAGEUP,
        Key::PageDown => keys::KEY_PAGEDOWN,
        Key::ArrowUp => keys::KEY_UP,
        Key::ArrowDown => keys::KEY_DOWN,
        Key::ArrowLeft => keys::KEY_LEFT,
        Key::ArrowRight => keys::KEY_RIGHT,
        Key::Minus => keys::KEY_MINUS,
        Key::Equals | Key::Plus => keys::KEY_EQUAL,
        Key::OpenBracket | Key::OpenCurlyBracket => keys::KEY_LEFTBRACE,
        Key::CloseBracket | Key::CloseCurlyBracket => keys::KEY_RIGHTBRACE,
        Key::Backslash | Key::Pipe => keys::KEY_BACKSLASH,
        Key::Semicolon | Key::Colon => keys::KEY_SEMICOLON,
        Key::Quote => keys::KEY_APOSTROPHE,
        Key::Backtick => keys::KEY_GRAVE,
        Key::Comma => keys::KEY_COMMA,
        Key::Period => keys::KEY_DOT,
        Key::Slash | Key::Questionmark => keys::KEY_SLASH,
        Key::Exclamationmark => keys::KEY_1,
        Key::Num0 => keys::KEY_0,
        Key::Num1 => keys::KEY_1,
        Key::Num2 => keys::KEY_2,
        Key::Num3 => keys::KEY_3,
        Key::Num4 => keys::KEY_4,
        Key::Num5 => keys::KEY_5,
        Key::Num6 => keys::KEY_6,
        Key::Num7 => keys::KEY_7,
        Key::Num8 => keys::KEY_8,
        Key::Num9 => keys::KEY_9,
        Key::A => keys::KEY_A,
        Key::B => keys::KEY_B,
        Key::C => keys::KEY_C,
        Key::D => keys::KEY_D,
        Key::E => keys::KEY_E,
        Key::F => keys::KEY_F,
        Key::G => keys::KEY_G,
        Key::H => keys::KEY_H,
        Key::I => keys::KEY_I,
        Key::J => keys::KEY_J,
        Key::K => keys::KEY_K,
        Key::L => keys::KEY_L,
        Key::M => keys::KEY_M,
        Key::N => keys::KEY_N,
        Key::O => keys::KEY_O,
        Key::P => keys::KEY_P,
        Key::Q => keys::KEY_Q,
        Key::R => keys::KEY_R,
        Key::S => keys::KEY_S,
        Key::T => keys::KEY_T,
        Key::U => keys::KEY_U,
        Key::V => keys::KEY_V,
        Key::W => keys::KEY_W,
        Key::X => keys::KEY_X,
        Key::Y => keys::KEY_Y,
        Key::Z => keys::KEY_Z,
        Key::F1 => keys::KEY_F1,
        Key::F2 => keys::KEY_F2,
        Key::F3 => keys::KEY_F3,
        Key::F4 => keys::KEY_F4,
        Key::F5 => keys::KEY_F5,
        Key::F6 => keys::KEY_F6,
        Key::F7 => keys::KEY_F7,
        Key::F8 => keys::KEY_F8,
        Key::F9 => keys::KEY_F9,
        Key::F10 => keys::KEY_F10,
        Key::F11 => keys::KEY_F11,
        Key::F12 => keys::KEY_F12,
        _ => return None,
    })
}
